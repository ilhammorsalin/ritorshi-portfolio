import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs"
import { join, relative } from "node:path"
import { execSync } from "node:child_process"

const ROOT = process.cwd()

function readJson(p) {
  return JSON.parse(readFileSync(p, "utf8"))
}

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name === ".next" || name === ".git") continue
    const full = join(dir, name)
    const st = statSync(full)
    if (st.isDirectory()) walk(full, acc)
    else acc.push(full)
  }
  return acc
}

const pkg = readJson(join(ROOT, "package.json"))
const deps = { ...pkg.dependencies, ...pkg.devDependencies }

let gitBranch = "unknown"
let gitStatus = ""
try {
  gitBranch = execSync("git branch --show-current", { cwd: ROOT }).toString().trim()
  gitStatus = execSync("git status --short", { cwd: ROOT }).toString().trim()
} catch {}

const srcFiles = walk(join(ROOT, "src")).map((f) => relative(ROOT, f))

function treeLines(dir, prefix = "") {
  const entries = readdirSync(dir)
    .filter((n) => !["node_modules", ".next", ".git"].includes(n))
    .sort()
  const out = []
  entries.forEach((name, i) => {
    const full = join(dir, name)
    const last = i === entries.length - 1
    const branch = last ? "└── " : "├── "
    out.push(prefix + branch + name)
    if (statSync(full).isDirectory()) {
      out.push(...treeLines(full, prefix + (last ? "    " : "│   ")))
    }
  })
  return out
}

const tree = treeLines(ROOT).join("\n")
const scriptList = Object.entries(pkg.scripts)
  .map(([k, v]) => `- \`npm run ${k}\` — \`${v}\``)
  .join("\n")
const srcList = srcFiles.map((f) => `- \`${f}\``).join("\n")

const publicFiles = existsSync(join(ROOT, "public"))
  ? readdirSync(join(ROOT, "public")).filter((f) => f !== ".gitkeep")
  : []
const publicList = publicFiles.length
  ? publicFiles.map((f) => `- \`public/${f}\``).join("\n")
  : "- (none)"

